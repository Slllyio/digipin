"""Render a steward result as Markdown (committed report and GitHub issue body)."""
from __future__ import annotations

ICON = {"ok": "🟢", "info": "🔵", "warn": "🟡", "fail": "🔴"}
ISSUE_TITLE = "Pipeline Steward: data pipeline health"


def to_markdown(result: dict) -> str:
    counts = {s: sum(1 for f in result["findings"] if f["severity"] == s) for s in ("fail", "warn", "info")}
    lines = [
        f"# Pipeline health {ICON[result['status']]} {result['status'].upper()}",
        "",
        f"Checked {result['source_count']} sources at {result['generated_at']}: "
        f"{counts['fail']} failing, {counts['warn']} warnings, {counts['info']} notes.",
        "",
        "| Source | Status | Rows | Last refreshed |",
        "|---|---|---|---|",
    ]
    for sid, s in result["sources"].items():
        rows = "" if s["rows"] is None else s["rows"]
        lines.append(f"| `{sid}` | {ICON[s['status']]} {s['status']} | {rows} | {s['generated_at'] or 'never'} |")
    actionable = [f for f in result["findings"] if f["severity"] in ("fail", "warn")]
    if actionable:
        lines += ["", "## Findings", ""]
        for f in actionable:
            hint = f" ({f['hint']})" if f["hint"] else ""
            lines.append(f"- {ICON[f['severity']]} **{f['source']}** · {f['check']}: {f['message']}{hint}")
    notes = [f for f in result["findings"] if f["severity"] == "info"]
    if notes:
        lines += ["", "<details><summary>Notes</summary>", ""]
        lines += [f"- **{f['source']}**: {f['message']}" for f in notes]
        lines += ["", "</details>"]
    lines += ["", "_Generated by `python -m pipeline.steward`. The tracking issue updates on every run "
              "and closes itself once everything is healthy._"]
    return "\n".join(lines) + "\n"
